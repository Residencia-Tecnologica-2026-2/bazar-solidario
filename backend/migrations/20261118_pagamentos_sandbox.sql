CREATE TABLE IF NOT EXISTS pagamentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id bigint NOT NULL UNIQUE REFERENCES pedidos(id),
    referencia varchar(255) NOT NULL UNIQUE,
    provedor_id varchar(255) UNIQUE,
    estado varchar(255) NOT NULL,
    checkout_url varchar(255),
    aviso varchar(250),
    liquido numeric(16,2),
    tarifa numeric(16,2),
    liquido_brecho numeric(16,2),
    atualizado_em timestamp(6)
);
